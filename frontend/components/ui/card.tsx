import * as React from "react"

import { neo } from "@/lib/neo"
import { cn } from "@/lib/utils"

function Card({
  className,
  size = "default",
  ...props
}: React.ComponentProps<"div"> & { size?: "default" | "sm" }) {
  return (
    <div
      data-slot="card"
      data-size={size}
      className={cn(
        "group/card flex flex-col gap-6 p-6 text-sm ring-0 data-[size=sm]:gap-4 data-[size=sm]:p-4",
        neo.panel,
        className
      )}
      {...props}
    />
  )
}

